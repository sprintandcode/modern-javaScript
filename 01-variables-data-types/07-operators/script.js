// 1. Arithmetic Operators

let x;
x = x + 5;  // additional operator
x = x - 5;  // subtraction operator
x = x * 5;  // multiplication operator
x = x / 5;  // divisional operator
x = x % 5;  // modulo operator 

// Concatenation - join strings together
word = 'Hello' + ' ' + 'World';
console.log(word)

// Exponent operator
let z = 2;
z = z ** 3;
console.log(z)

// Increment operator
z++;
console.log(z)

// Decrement operator
z--;
console.log(z)



